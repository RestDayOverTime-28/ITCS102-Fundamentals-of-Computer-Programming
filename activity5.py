a = 6
b = 7

sum = a + b
diff = a - b
product = a * b
division = a / b
floorDivision = a // b
exponential = a ** b
modulus = a % b

print("The sum of", a, "and", b, "is:", sum)
print("The difference of", a, "and", b, "is:", diff)
print("The product of", a, "and", b, "is:", product)
print("The quotient of", a, "and", b, "is:", division)
print("The remainder of", a, "and", b, "is:", modulus)
print("The result of", a, "raised to the power of", b, "is:", exponential)
print("The floor division of", a, "and", b, "is:", floorDivision)

